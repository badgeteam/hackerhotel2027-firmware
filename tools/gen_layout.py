#!/usr/bin/env python3
"""Generate layout.c (the LED layout tables apps get through hh_api_t) from
webui/board_data.js, the board data the web UI draws the badge from.

A slot is the LED's place in the matrix: row (COM, PB0..PB15) * 24 + col
(PWM channel, PA0..PA23), the same index FRAME_CHUNK uses.

- GRID: the 208 mono LEDs of the centre grid, on a 2 mm pitch, as 16 rows
  of 17 columns; the corners of the octagon have no LED (HH_NONE).
- EDGE: the 71 other mono LEDs, along the outline, clockwise from the top.
- RGB: the 35 RGB LEDs (red, green and blue slot), with the arm they sit on
  (0 = top arm, then clockwise) and their rank on it (0 = nearest the centre).

- ORDER: every slot once, in a spatial order (the grid row by row, then
  EDGE, then RGB as red, green, blue per LED). LA03 animations
  (webui/compression.js) code their pixels in this order, so neighbours
  on the badge are neighbours in the stream.

- GAMMA: brightness 0..255 as the web interface shows it (like a screen,
  sRGB) to PWM duty: gamma 2.2. LEDs are linear, so without it every
  mid-level value comes out far too bright.

It writes layout.c (for the firmware) and webui/layout_data.js (for the
web interface's LA03 codec): tools/gen_layout.py
"""
import json
import math
import os
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
COLS = 24
NONE = 0xFFFF
GRID_W, GRID_H, PITCH = 17, 16, 2.0


def load():
    s = open(os.path.join(HERE, "..", "webui", "board_data.js")).read()
    return json.loads(s[s.index("{"):s.rindex("}") + 1])


def angle(x, y):
    """Clockwise from the top, in degrees; board y grows downwards."""
    return math.degrees(math.atan2(x, -y)) % 360


def main():
    board = load()
    leds = board["leds"]
    xs = [l["x"] for l in leds]
    ys = [l["y"] for l in leds]

    # The grid's columns and rows are the x and y values that many LEDs
    # share; an outline LED shares its x or y with one or two others at most.
    def lines(values, n):
        count = Counter(round(v, 2) for v in values)
        on = sorted(v for v, c in count.items() if c >= 5)
        assert len(on) == n and all(abs(b - a - PITCH) < 0.02 for a, b in zip(on, on[1:])), on
        return on[0]

    x0 = lines(xs, GRID_W)
    y0 = lines(ys, GRID_H)
    grid = [[NONE] * GRID_W for _ in range(GRID_H)]
    in_grid = set()
    for l in leds:
        gx = (l["x"] - x0) / PITCH
        gy = (l["y"] - y0) / PITCH
        if abs(gx - round(gx)) < 0.005 and abs(gy - round(gy)) < 0.005 and 0 <= round(gx) < GRID_W and 0 <= round(gy) < GRID_H:
            slot = l["row"] * COLS + l["col"]
            grid[round(gy)][round(gx)] = slot
            in_grid.add(slot)
    cx = x0 + PITCH * (GRID_W - 1) / 2
    cy = y0 + PITCH * (GRID_H - 1) / 2

    edge = sorted((l for l in leds if l["row"] * COLS + l["col"] not in in_grid),
                  key=lambda l: angle(l["x"] - cx, l["y"] - cy))
    edge = [l["row"] * COLS + l["col"] for l in edge]

    rgb = []
    for l in board["rgb_leds"]:
        a = angle(l["x"] - cx, l["y"] - cy)
        arm = round(a / 72) % 5
        rgb.append(dict(l, arm=arm, dist=math.hypot(l["x"] - cx, l["y"] - cy)))
    for arm in range(5):
        on_arm = sorted((r for r in rgb if r["arm"] == arm), key=lambda r: r["dist"])
        for rank, r in enumerate(on_arm):
            r["rank"] = rank
    rgb.sort(key=lambda r: (r["arm"], r["rank"]))

    n_grid = sum(v != NONE for row in grid for v in row)
    assert n_grid == 208 and len(edge) == 71 and len(rgb) == 35, (n_grid, len(edge), len(rgb))

    order = [v for row in grid for v in row if v != NONE] + edge
    for r in rgb:
        order += [r["row"] * COLS + r["col"], r["green_row"] * COLS + r["col"], r["blue_row"] * COLS + r["col"]]
    assert sorted(order) == list(range(COLS * 16)), "the LEDs must fill every slot once"

    with open(os.path.join(HERE, "..", "webui", "layout_data.js"), "w") as js:
        js.write("// Generated by tools/gen_layout.py from board_data.js; do not edit.\n")
        js.write("// LA03's pixel order and the centre grid (null: no LED), see compression.js.\n")
        js.write("const LAYOUT_ORDER = %s;\n" % json.dumps(order))
        js.write("const LAYOUT_GRID = %s;\n" % json.dumps([[None if v == NONE else v for v in row] for row in grid]))

    out = open(os.path.join(HERE, "..", "layout.c"), "w")
    out.write("// Generated by tools/gen_layout.py from webui/board_data.js; do not edit.\n")
    out.write('#include "layout.h"\n\n')
    out.write("const uint16_t layout_grid[HH_GRID_H][HH_GRID_W] = {\n")
    for row in grid:
        out.write("    {" + ", ".join("HH_NONE" if v == NONE else "%3d" % v for v in row) + "},\n")
    out.write("};\n\nconst uint16_t layout_edge[HH_EDGE_COUNT] = {\n")
    for i in range(0, len(edge), 12):
        out.write("    " + ", ".join("%3d" % v for v in edge[i:i + 12]) + ",\n")
    out.write("};\n\nconst hh_rgb_t layout_rgb[HH_RGB_COUNT] = {\n")
    for r in rgb:
        out.write("    {%3d, %3d, %3d, %d, %d}, // %s\n" % (
            r["row"] * COLS + r["col"], r["green_row"] * COLS + r["col"], r["blue_row"] * COLS + r["col"],
            r["arm"], r["rank"], r["ref"]))
    out.write("};\n\nconst uint16_t layout_order[HH_SLOTS] = {\n")
    for i in range(0, len(order), 16):
        out.write("    " + ", ".join("%3d" % v for v in order[i:i + 16]) + ",\n")
    out.write("};\n\nconst uint8_t layout_gamma[256] = {\n")
    gamma = [round(255 * (i / 255) ** 2.2) for i in range(256)]
    for i in range(0, 256, 16):
        out.write("    " + ", ".join("%3d" % v for v in gamma[i:i + 16]) + ",\n")
    out.write("};\n")
    out.close()


main()
