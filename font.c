static const uint8_t* glyph(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');  // no lower case yet
    return s_glyphs[c >= ' ' && c <= '_' ? c - ' ' : 0];
}

int Text_Width(const char* text) {
    int n = 0;
    while (text[n]) n++;
    return n ? n * FONT_ADVANCE - 1 : 0;
}

int Text_Draw(int x, int y, const char* text, uint8_t value) {
    for (int k = 0; text[k]; k++) {
        int x0 = x + k * FONT_ADVANCE;
        if (x0 >= HH_GRID_W || x0 + FONT_W <= 0) continue;
        const uint8_t* g = glyph(text[k]);
        for (int dx = 0; dx < FONT_W; dx++) {
            int col = x0 + dx;
            if (col < 0 || col >= HH_GRID_W) continue;
            for (int dy = 0; dy < FONT_H; dy++) {
                int row = y + dy;
                if (!(g[dx] >> dy & 1) || row < 0 || row >= HH_GRID_H) continue;
                uint16_t slot = layout_grid[row][col];
                if (slot != HH_NONE) LEDMatrix_SetPixel(slot / HH_COLS, slot % HH_COLS, value);
            }
        }
    }
    return Text_Width(text);
}
