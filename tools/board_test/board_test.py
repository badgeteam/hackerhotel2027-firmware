#!/usr/bin/env python3
"""Tests for tools/extract_board_data.py.

1. A small made-up board: the S-expression parser, the net logic (series
   resistors, PA/PB pins, RGB pads, undriveable LEDs), buttons, and the
   outline (the biggest gr_poly, a hole left out, other Edge.Cuts shapes
   refused).
2. The real board, when there is one (see extract_board_data.py for where
   it looks): regenerate board_data.js. It must be byte for byte
   webui/board_data.js (only the data, for a plain .kicad_pcb), and the
   LEDs must meet tools/gen_layout.py's rules. Without the board this part prints SKIP,
   but when HH27_HW or CI is set a missing board or HW_REV commit fails,
   so CI can't go green with the check off.
"""
import json
import os
import subprocess
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.dirname(HERE)
sys.path.insert(0, TOOLS)
import extract_board_data as E  # noqa: E402

COLS, ROWS, PITCH = 24, 16, 2.0


def pad(num, net, func=None, old=False):
    net = f'(net 7 "{net}")' if old else f'(net "{net}")'
    pf = f' (pinfunction "{func}")' if func else ""
    return f'(pad "{num}" smd rect (at 0 0) {net}{pf})'


def fp(lib, ref, at, *pads, old=False):
    name = f'(fp_text reference "{ref}" (at 0 0))' if old else f'(property "Reference" "{ref}" (at 0 0 90))'
    return f'(footprint "{lib}" (layer "F.Cu") (at {at}) {name} {" ".join(pads)})'


FAKE = "(kicad_pcb (version 20260206)\n" + "\n".join([
    fp("ch643:LQFP", "U1", "0 0",
       pad("1", "PWM0", "PA0/T1"), pad("2", "/R3b", "PA3"), pad("3", "C1", "PB1/X"),
       pad("4", "C2", "PB2"), pad("5", "C3", "PB3"), pad("6", "BTN1", "PC5")),
    fp("Resistor_SMD:R_0402", "R1", "1 1", pad("1", "PWM0"), pad("2", "/R0b")),
    fp("led_no_silk:LED_0402_1005Metric_nosilk", "D2", "-10.8 -11.915 90",
       pad("1", "C1", "K_1"), pad("2", "/R0b", "A_2")),
    fp("led_no_silk:LED_0402_1005Metric_nosilk", "D3", "4 5",
       pad("1", "C2", old=True), pad("2", "/R3b", old=True), old=True),
    fp("led:LED-SMD-4P_NH-B1515RGBA-GF", "D1", "0 -38.5 -45",
       pad("1", "C1"), pad("2", "/R0b"), pad("3", "C3"), pad("4", "C2")),
    fp("led_no_silk:LED_0402_1005Metric_nosilk", "D9", "7 8 180",
       pad("1", "C2"), pad("2", "nowhere")),
    fp("LED_SMD:LED_0603_1608Metric", "D10", "9 9", pad("1", "C1"), pad("2", "/R0b")),
    fp("pushbutton:SW-SMD", "SW2", "42.38 -15.646516 -135",
       pad("1", "unconnected-(SW2-A-Pad1)"), pad("2", "BTN2"), pad("3", "GND")),
    fp("pushbutton:SW-SMD", "SW1", "-41.943483 -18.09 -45", pad("2", "BTN1"), pad("3", "GND")),
    '(gr_poly (pts (xy 1 1) (xy 2 1) (xy 2 2)) (layer "Edge.Cuts"))',
    '(gr_poly (pts (xy 0 0) (xy 10 0) (xy 15 5.5) (xy 10 10) (xy 0 10)) (layer "Edge.Cuts"))',
    '(gr_circle (center 5 5) (end 6 5) (layer "Edge.Cuts"))',
    '(gr_poly (pts (xy -50 -50) (xy 50 -50) (xy 50 50)) (layer "F.SilkS"))',
    '(gr_line (start -50 -50) (end 50 50) (layer "F.SilkS"))',
    '(gr_text "a \\"quoted\\" (text)" (at 0 0) (layer "F.SilkS"))',
]) + "\n)\n"


def test_fake():
    tree = E.parse(FAKE)
    assert tree[0] == "kicad_pcb"
    assert E.kid(tree, "gr_text")[1] == 'a "quoted" (text)'
    d = E.board_data(FAKE)
    assert d["leds"] == [
        {"ref": "D2", "x": -10.8, "y": -11.915, "rot": 90.0, "row": 1, "col": 0},
        {"ref": "D3", "x": 4.0, "y": 5.0, "rot": 0.0, "row": 2, "col": 3},
    ], d["leds"]
    assert d["rgb_leds"] == [{"ref": "D1", "x": 0.0, "y": -38.5, "rot": -45.0, "row": 1,
                              "col": 0, "green_row": 2, "blue_row": 3}], d["rgb_leds"]
    assert d["undriveable"] == [{"ref": "D9", "x": 7.0, "y": 8.0, "rot": 180.0}], d["undriveable"]
    assert [(b["ref"], b["label"]) for b in d["buttons"]] == [("SW1", "BTN1"), ("SW2", "BTN2")]
    assert d["outline"] == [[0, 0], [10, 0], [15, 5.5], [10, 10], [0, 10]], d["outline"]
    for bad in ('(gr_line (start 0 0) (end 10 0) (layer "Edge.Cuts"))',
                '(gr_poly (pts (xy 0 0) (arc (start 4 0) (mid 6 2) (end 4 4))) (layer "Edge.Cuts"))',
                '(gr_circle (center 5 5) (end 6 5) (layer "Edge.Cuts"))'):
        try:
            E.outline(E.parse(f"(kicad_pcb {bad})"))
        except SystemExit:
            continue
        raise AssertionError(f"outline() took {bad}")
    text = E.render(d, "fake")
    assert text.startswith("// Generated by tools/extract_board_data.py") and text.endswith("};\n")
    assert json.loads(text[text.index("{"):text.rindex("}") + 1]) == d
    print("board_test: made-up board OK")


def load_text(s):
    return json.loads(s[s.index("{"):s.rindex("}") + 1])


def check_layout(d):
    """tools/gen_layout.py's rules: 208 grid + 71 edge LEDs, 35 RGB, every slot once."""
    leds = d["leds"]

    def first_line(values, n):
        count = Counter(round(v, 2) for v in values)
        on = sorted(v for v, c in count.items() if c >= 5)
        assert len(on) == n and all(abs(b - a - PITCH) < 0.02 for a, b in zip(on, on[1:])), on
        return on[0]

    x0 = first_line([l["x"] for l in leds], 17)
    y0 = first_line([l["y"] for l in leds], 16)
    grid = 0
    for l in leds:
        gx, gy = (l["x"] - x0) / PITCH, (l["y"] - y0) / PITCH
        if (abs(gx - round(gx)) < 0.005 and abs(gy - round(gy)) < 0.005
                and 0 <= round(gx) < 17 and 0 <= round(gy) < 16):
            grid += 1
    assert (grid, len(leds) - grid, len(d["rgb_leds"])) == (208, 71, 35), (grid, len(leds) - grid)
    slots = [l["row"] * COLS + l["col"] for l in leds]
    for l in d["rgb_leds"]:
        slots += [r * COLS + l["col"] for r in (l["row"], l["green_row"], l["blue_row"])]
    dup = [s for s, n in Counter(slots).items() if n > 1]
    assert not dup, f"slots with more than one LED: {dup}"
    assert sorted(slots) == list(range(COLS * ROWS)), "the LEDs must fill every slot once"


def test_board():
    strict = os.environ.get("HH27_HW") or os.environ.get("CI")

    def skip(why):
        if strict:  # asked for on purpose, or in CI: a skip would hide the check
            sys.exit(f"board_test: FAIL the real board: {why} (HH27_HW or CI is set)")
        print(f"board_test: SKIP the real board: {why}")

    where = E.find_board(None)
    if not where:
        return skip("no hackerhotel2027-hardware (set HH27_HW or clone it next to this repository)")
    git = os.path.exists(os.path.join(where, ".git"))
    if git and subprocess.run(["git", "-C", where, "cat-file", "-e", E.HW_REV + "^{commit}"],
                              capture_output=True).returncode:
        return skip(f"{where} has no commit {E.HW_REV[:7]} (git fetch)")
    new = subprocess.run([sys.executable, os.path.join(TOOLS, "extract_board_data.py"), where,
                          "-o", "-"], check=True, capture_output=True, text=True).stdout
    old = open(os.path.join(TOOLS, "..", "webui", "board_data.js")).read()
    if git:
        assert new == old, ("webui/board_data.js is not what tools/extract_board_data.py makes: "
                            "run it and tools/gen_layout.py, and commit the result")
    else:  # a plain .kicad_pcb: the header can't name the commit, so compare the data
        assert load_text(new) == load_text(old), "webui/board_data.js does not match the board"
    data = load_text(new)
    check_layout(data)
    print(f"board_test: real board OK ({len(data['leds'])} mono, {len(data['rgb_leds'])} RGB, "
          f"{len(data['outline'])} outline points, from {where})")


if __name__ == "__main__":
    test_fake()
    test_board()
